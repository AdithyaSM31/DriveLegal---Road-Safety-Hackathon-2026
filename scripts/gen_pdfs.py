from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
import os

os.makedirs('frontend/assets', exist_ok=True)

# Generate Traffic Laws Report
c = canvas.Canvas('frontend/assets/Traffic_Laws_Report.pdf', pagesize=letter)
c.setFont("Helvetica-Bold", 24)
c.drawString(100, 700, "DriveLegal - Traffic Laws Report")
c.setFont("Helvetica", 12)
c.drawString(100, 660, "This is a detailed summary of current traffic laws and violations.")
c.drawString(100, 640, "Generated by DriveLegal Hackathon Prototype.")
c.drawString(100, 600, "1. Over Speeding - Rs. 1000")
c.drawString(100, 580, "2. No Helmet - Rs. 1000")
c.drawString(100, 560, "3. Signal Jumping - Rs. 5000")
c.save()

# Generate Analytics Report
c = canvas.Canvas('frontend/assets/Road_Safety_Analytics.pdf', pagesize=letter)
c.setFont("Helvetica-Bold", 24)
c.drawString(100, 700, "DriveLegal - Road Safety Analytics")
c.setFont("Helvetica", 12)
c.drawString(100, 660, "This report contains analytics data for the current jurisdiction.")
c.drawString(100, 640, "Generated by DriveLegal Hackathon Prototype.")
c.drawString(100, 600, "Top Violations:")
c.drawString(120, 580, "- Over Speeding: 35%")
c.drawString(120, 560, "- No Helmet: 25%")
c.drawString(120, 540, "- Signal Jumping: 15%")
c.save()

print("PDFs generated successfully.")
